// LineMarker — служебная приставка каждой обычной строки тела.
//
// Она и есть граница доверия между шапкой, которую печатает мост, и телом,
// пришедшим из сети. Работает ОТСУТСТВИЕМ: тело не может убрать маркер у своей
// строки — только добавить свой, и тогда выйдет приставка внутри приставки.
// Значит строка без маркера гарантированно наша.
//
// Обратное устройство — метить шапку — не работает вовсе: тело напечатает
// такую же приставку, и различить будет нечем.
const LineMarker = "│ "

// TruncationMark — знак того, что тело показано не целиком.
const TruncationMark = "…"

// Rendered — показ письма и то, полон ли он.
//
// Показ ОДИН. Раньше их было два: разметка и «запасной» текст без разметки на
// случай отказа. Запасной убран, и убран по итогам живой проверки: текст без
// parse_mode Telegram разбирает точно так же — команда из тела остаётся
// командой. Такой запас не страховал, а прятал дыру, и держался он только
// тестом, запрещающим его подключать; при выпуске этот тест сняли бы первым.
// Безопасный запас — profileFullPre, он получается тем же механизмом.
type Rendered struct {
	// HTML — выбранный показ, отправляется с parse_mode=HTML.
	//
	// Показ ОДИН. Запаса рядом с ним нет намеренно: аварийный повтор живёт в
	// клиенте и теперь общий для всех наших сообщений — при отказе Telegram
	// он снимает разметку, заново экранирует текст и заворачивает в один
	// моноширинный блок. Держать рядом второй, свой, значит завести два
	// механизма на одну задачу: поправят один и решат, что закрыли вопрос.
	HTML string
	// Truncated — показано не всё письмо.
	//
	// Считается сравнением ПОКРЫТИЯ с длиной всего канонического потока, а не
	// тем, что случилось по дороге. Поэтому знак не может появиться там, где
	// показан весь текст: прежняя версия объявляла обрезку по внутреннему
	// состоянию прохода и на узкой полосе пределов лгала.
	Truncated bool
	// Profile — какое оформление в итоге выбрано. Нужен тестам и будущему
	// журналу: по нему видно, почему письмо выглядит именно так.
	Profile string
}

// profile — что этому кандидату разрешено рисовать.
//
// Набор ФИКСИРОВАН для кандидата и не зависит от остатка предела — в этом всё
// дело. Пока решение «открыть ли тег» принималось по остатку, одна лишняя
// руна включала дорогое оформление и отнимала два десятка рун текста: показ
// при большем пределе становился хуже. Кандидат с фиксированной политикой
// такого сделать не может: место сдвигает только точку обрыва.
type profile struct {
	name string
	// links — разрешена ли наша ссылка. Дороже всего: адрес в href дублирует
	// видимый адрес, то есть лексема оплачивается дважды.
	links bool
	// styles — жирный и курсив.
	styles bool
	// authorCode — авторские code и pre своими тегами.
	//
	// Выключенные, они показываются обычными строками с маркером. Это не
	// «беднее»: тег платится один раз, а маркер — на каждой строке, поэтому
	// на многострочном коде выключение дороже включения. Отсюда и правило
	// сравнивать кандидатов по факту, а не по порядку богатства.
	authorCode bool
	// fullPre — всё тело одним моноширинным блоком, как сегодня в бою.
	//
	// Маркера строк здесь нет и не должно быть: границу доверия держит сам
	// блок, а маркер попал бы в буфер при копировании. Подавление опасных
	// лексем этот блок даёт сам — проверено живьём.
	fullPre bool
}

// profiles — кандидаты по убыванию богатства.
//
// Порядок задан списком, а не отношением включения: профили не вложены друг в
// друга (см. authorCode). Этот же порядок разрешает ничью по покрытию.
var profiles = []profile{
	{name: "rich", links: true, styles: true, authorCode: true},
	{name: "no-links", styles: true, authorCode: true},
	{name: "no-style", authorCode: true},
	{name: "marked-code"},
	{name: "full-pre", fullPre: true},
}

// Общий блок — обычный пятый кандидат, а не отложенный запас. Аварийный
// повтор при отказе Telegram делает клиент, одинаково для всех сообщений;
// здесь этот профиль участвует в сравнении наравне с прочими и побеждает
// тогда, когда показывает больше текста.

// maxTraversals — сколько обходов дерева стоит один показ.
//
// Два на кандидата: второй нужен, потому что знак обрезки меняет предел, а
// изменённый предел меняет решения. Граница закреплена тестом намеренно:
// шестой профиль добавится незаметно, а стоимость вырастет молча.
const maxTraversals = 2 * profileCount

// profileCount — сколько кандидатов сравнивается. Проверяется тестом против
// длины списка: шестой профиль иначе добавится молча.
const profileCount = 5

// RenderBody превращает markdown тела письма в показ для Telegram.
//
// В боевом пути НЕ ВЫЗЫВАЕТСЯ: показ письма по-прежнему идёт через
// FormatMessage с моноширинным телом. Включение ждёт подавителя опасных
// лексем — живая проверка показала, что вне code и pre строка тела становится
// действием человека.
//
// budget — предел ГОТОВОЙ разметки в рунах. Считать по исходному тексту
// нельзя: экранирование раздувает строку вчетверо на каждой угловой скобке, а
// теги добавляются сверху. Вылезший за предел пост режет общий Split — по
// рунам, посреди тега, — и Telegram отвергает сообщение целиком.
func RenderBody(body string, budget int) Rendered {
	source, cutInput := boundInput(body)

	session := &renderSession{doc: parseSource(source), source: source}
	best := session.choose(budget, cutInput)

	return Rendered{HTML: best.html, Truncated: best.truncated, Profile: best.name}
}

// renderSession — один разбор и все кандидаты по нему.
//
// Счётчик обходов держится здесь, а не в пакетной переменной: так его видит
// тест, а бой не видит вовсе.
type renderSession struct {
	doc        ast.Node
	source     []byte
	traversals int
}

// choose выбирает показ: сначала безопасные, потом самое полное, потом самое
// богатое.
//
// Кандидаты перебираются от богатого к бедному, и первый же, показавший
// письмо целиком, побеждает сразу: полнее не покажет никто, а богаче некому.
// Для влезающих тел это два обхода вместо десяти.
func (s *renderSession) choose(budget int, cutInput bool) candidate {
	var best candidate
	for i, p := range profiles {
		got := s.finalize(budget, p, cutInput)
		if i == 0 || got.covered > best.covered {
			best = got
		}
		if got.covered >= got.total {
			// Полнее уже не покажет никто, а богаче некому: список идёт от
			// богатого к бедному, ничья решается в пользу первого.
			break
		}
	}
	return best
}

// candidate — готовый показ одного профиля.
type candidate struct {
	name      string
	html      string
	covered   int
	total     int
	truncated bool
}

// finalize доводит кандидата до конца — со знаком обрезки, если он нужен.
//
// Знак приписывается ПОСЛЕ сравнения покрытия с полным потоком, а не по тому,
// оборвался ли проход. Сравнивать кандидатов можно только такими,
// доведёнными: знак съедает руну, руна меняет решения, и заготовки сравнивать
// бессмысленно.
func (s *renderSession) finalize(budget int, p profile, cutInput bool) candidate {
	html, covered, total := s.renderOnce(budget, p)
	if covered >= total && !cutInput {
		return candidate{name: p.name, html: html, covered: covered, total: total}
	}

	room := budget - runes(TruncationMark)
	if room < 0 {
		// Места нет даже под знак: показывать нечего.
		return candidate{name: p.name, total: total, truncated: true}
	}

	// Второй проход показать БОЛЬШЕ первого не может: предел меньше, а
	// политика профиля от предела не зависит. Раньше могло — оформление
	// включалось по остатку, и меньший предел иногда вмещал всё целиком;
	// тогда здесь стояла проверка «а вдруг влезло». Теперь она была бы
	// мёртвой веткой, и её нет.
	html, covered, total = s.renderOnce(room, p)
	return candidate{
		name:      p.name,
		html:      html + TruncationMark,
		covered:   covered,
		total:     total,
		truncated: true,
	}
}

// renderOnce собирает один показ и говорит, сколько текста письма в него вошло.
//
// Возвращает и ПОЛНУЮ длину канонического потока: обход продолжается после
// обрыва, только уже без записи. Так длина достаётся бесплатно, без отдельного
// прохода, и она одна для всех профилей — оформление на неё не влияет.
func (s *renderSession) renderOnce(budget int, p profile) (string, int, int) {
	s.traversals++

	r := newRenderer(budget, p)
	if p.fullPre {
		r.openFullPre()
	}
	r.walk(s.doc, s.source)
	html, _ := r.finish()
	return html, r.covered, r.seen
}

// boundInput приводит тело к безопасному виду и ограничивает его ВХОД.
//
// Предел входа отдельный от предела показа и нужен раньше него: без него
// разбору достаётся тело любой длины, а дерево строится целиком, чтобы почти
// всё потом выбросить. BodyLimit — та же граница, которой канал живёт
// сегодня: канал остаётся витриной, полное письмо лежит в ящике.
//
// Считается по рунам уже нормализованного текста, а не по байтам исходного:
// граница должна совпадать с тем, что человек видит.
func boundInput(body string) ([]byte, bool) {
	safe := stripBidiControls(normalizeLineBreaks(body))

	runes := []rune(safe)
	if len(runes) <= BodyLimit {
		return []byte(safe), false
	}
	return []byte(string(runes[:BodyLimit])), true
}

func parseSource(source []byte) ast.Node {
	md := goldmark.New(goldmark.WithExtensions(extension.Linkify))
	return md.Parser().Parse(text.NewReader(source))
}

// lineBreakRunes — всё, что клиент показывает как перевод строки.
//
// Перечислены кодами, а не символами: в исходнике они невидимы, и правка
// вслепую ломала бы список молча.
//
// Список полный намеренно: маркер ставится по строкам, а строка у нас и строка
// на экране — разные вещи. strings.Split по "\n" не видит U+2028, тогда как
// клиент показывает его переносом, и поддельная шапка после такого символа
// оказалась бы без маркера, то есть выглядела бы нашей.
var lineBreakRunes = []rune{
	'\r',   // CR
	'\v',   // VT
	'\f',   // FF
	0x0085, // NEL
	0x2028, // LINE SEPARATOR
	0x2029, // PARAGRAPH SEPARATOR
}

// normalizeLineBreaks сводит все виды переводов строки к одному.
//
// Замена, а не удаление: удаление склеило бы слова и исказило письмо.
func normalizeLineBreaks(s string) string {
	s = strings.ReplaceAll(s, "\r\n", "\n")
	return strings.Map(func(r rune) rune {
		for _, br := range lineBreakRunes {
			if r == br {
				return '\n'
			}
		}
		return r
	}, s)
}

// stripBidiControls убирает управляющие символы направления письма.
//
// Они меняют ПОРЯДОК отображения, не меняя строку: маркер стоит первым в
// байтах и может оказаться не первым на экране. Один невидимый символ отменял
// бы всю границу.
//
// Набор берётся из таблицы Unicode, а не переписывается руками: рукописный
// список устаревает молча при следующем обновлении стандарта. Здесь именно
// удаление — в тексте письма эти символы ничего не значат, в отличие от
// переводов строки.
func stripBidiControls(s string) string {
	return strings.Map(func(r rune) rune {
		if unicode.Is(unicode.Bidi_Control, r) {
			return -1
		}
		return r
	}, s)
}

// richRenderer пишет разметку ПО ХОДУ обхода дерева.
//
// Устроен состоянием, а не постобработкой готовой строки, и это главное в нём.
// Прежняя версия собирала HTML, потом резала его по переводам строк и
// приписывала маркер — из-за чего маркер попадал ВНУТРЬ жирного, пустые строки
// оставались без него, а распознавание опасных токенов вынуждено было гадать
// по первому символу, потеряв структуру. Здесь рендерер знает, где он: начало
// строки, внутри выделения, внутри блока кода.
type richRenderer struct {
	out strings.Builder
	// budget — сколько рун ещё можно записать всего.
	budget int
	// reserve — сколько из них уже обещано концовке: закрывающие теги для
	// всего, что открыто сейчас.
	//
	// Без него предел соблюдался бы только до последнего текста, а закрытие
	// тегов вылезало бы за него — и вылезало бы ровно в том случае, когда
	// места и так нет. Тогда общий Split режет пост по рунам посреди тега,
	// и Telegram отвергает сообщение целиком: разметка не сбалансирована.
	reserve int
	// frames — открытые сейчас участки разметки, в порядке открытия.
	//
	// Нужны, чтобы перенос строки закрыл их, поставил маркер вне разметки и
	// открыл заново. Иначе маркер окажется частью выделения и перестанет
	// выглядеть одинаково — а он обязан выглядеть одинаково, иначе по нему
	// нельзя судить.
	frames      []tagFrame
	nextFrameID int
	atLineStart bool
	truncated   bool
	// policy — что этому показу разрешено рисовать.
	//
	// Набор фиксирован на весь проход: решение об оформлении принимает
	// профиль, а не остаток предела. Пока решал остаток, лишняя руна включала
	// дорогой тег и отнимала два десятка рун текста.
	policy profile
	// covered — сколько рун письма ЗАПИСАНО, seen — сколько встречено.
	//
	// Считаются руны исходного текста, а не вывода: экранирование раздувает
	// одну скобку вчетверо, теги добавляются сверху, и длина вывода растёт
	// вместе с оформлением. Мерить показ ею — значит счесть лучшим кандидата,
	// потратившего больше всех места на разметку.
	//
	// seen считается и после обрыва: обход продолжается без записи, и полная
	// длина потока достаётся тем же проходом, без отдельного.
	covered int
	seen    int
	// protected — глубина зоны, где подавлять уже нечего.
	//
	// Внутри авторских code и pre Telegram не распознаёт ничего — проверено
	// живьём, — и обёртка там была бы вложенным code, которого Telegram не
	// принимает. Внутри нашей ссылки тоже: её видимый текст равен адресу,
	// который мы сами и проверили.
	protected int
	// pending — лексема перешла границу узла и продолжается дальше.
	//
	// Разбор режет текст по своим правилам, а Telegram смотрит на готовую
	// строку целиком: «@agent_bot» приходит двумя узлами, потому что
	// подчёркивание могло оказаться выделением. Обернув только первый,
	// мы оставили бы «bot» голым — и упоминание распозналось бы как ни в чём
	// не бывало.
	pending bool
	// listDepth, quoteDepth — структурные приставки текущей строки.
	//
	// Приставки печатаются КАЖДОЙ строке, а не только первой строке блока.
	// Вторая строка цитаты без «> » неотличима от обычного текста письма — а
	// цитата ровно то место, где чужие слова обязаны быть видны чужими. С
	// вложенным списком то же самое: без отступа вложенный пункт выглядит
	// соседним, и список врёт о своей структуре.
	//
	// Идут ПОСЛЕ маркера строки: маркер обязан оставаться первым, иначе по
	// нему нельзя судить.
	// indent — сколько пробелов приставлять строкам внутри списка.
	//
	// Хранится в пробелах, а не в уровнях, потому что строк внутри пункта две
	// разновидности: первая начинается с «• », продолжение — с пустого места
	// той же ширины. Без этого продолжение пункта неотличимо от обычной
	// строки письма.
	indent     int
	quoteDepth int
}

// tagFrame — участок разметки как ВЛАДЕНИЕ, а не строка в стеке.
//
// Различие существенное. Пока стек был списком имён, узел, которому не хватило
// места на свой тег, всё равно звал закрытие — и снимал чужой, открытый выше.
// Вывод оставался сбалансированным, поэтому проверка баланса дефект не видела,
// а текст после этого места выходил без стиля, который на самом деле был
// открыт: «*A **B** C*» на тесном пределе давал «<i>A B</i> C».
//
// Поэтому фрейм заводится ВСЕГДА, даже когда открыть тег не удалось, и
// закрыть можно только свой фрейм. live говорит, открыт ли он физически
// прямо сейчас: перенос строки закрывает теги, не трогая владение, а на новой
// строке пытается открыть их заново.
type tagFrame struct {
	// id — самоличность фрейма.
	//
	// Не имя и не место в стеке: вложенность одинаковых тегов бывает на самом
	// деле — «*A *B* C*» даёт «<i>A <i>B</i> C</i>», — и по имени свой фрейм
	// от чужого не отличить.
	id   int
	tag  string
	open string
	live bool
}

func newRenderer(budget int, p profile) *richRenderer {
	return &richRenderer{
		budget:      budget,
		policy:      p,
		atLineStart: true,
	}
}

// openFullPre открывает блок, в который уйдёт всё тело.
//
// Отдельный вход, а не ветка обхода: в этом показе нет ни маркеров, ни
// вложенных тегов. Приставки строк — «> », буллет, отступ — печатаются и
// здесь: без них цитата и список слиплись бы в сплошной текст.
func (r *richRenderer) openFullPre() {
	// Сам тег печатается ДО всяких приставок — потому atLineStart временно
	// снят: иначе «> » первой строки оказалось бы снаружи блока.
	r.atLineStart = false
	r.openTag("pre")

	// А дальше строки внутри блока начинаются как обычные: со своими
	// приставками, но без маркера.
	r.atLineStart = true
}

func runes(s string) int { return len([]rune(s)) }

// avail — сколько рун можно записать прямо сейчас, не съев концовку.
func (r *richRenderer) avail() int { return r.budget - r.reserve }

// finish закрывает всё открытое и возвращает результат.
func (r *richRenderer) finish() (string, bool) {
	for len(r.frames) > 0 {
		r.dropFrame()
	}
	return strings.TrimRight(r.out.String(), "\n"), r.truncated
}

// raw пишет уже готовый кусок, если он влезает в остаток.
func (r *richRenderer) raw(s string) bool {
	if r.truncated {
		return false
	}
	cost := runes(s)
	if cost > r.avail() {
		r.cut()
		return false
	}
	r.budget -= cost
	r.out.WriteString(s)
	return true
}

// cut отмечает обрезку: дальше не пишем ничего.
//
// Сам знак здесь не ставится — его допишет renderBody после второго прохода.
func (r *richRenderer) cut() {
	r.truncated = true
}

// startLine ставит маркер, если строка ещё не начата.
func (r *richRenderer) startLine() {
	if !r.atLineStart {
		return
	}
	r.atLineStart = false
	if !r.policy.fullPre {
		// Внутри общего блока маркера нет: границу держит сам блок, а маркер
		// попал бы в буфер при копировании. Приставки печатаются и там —
		// «не входит в покрытие» не значит «не выводится»: без них цитаты и
		// списки в общем блоке слиплись бы в сплошной текст.
		r.raw(LineMarker)
	}

	for i := 0; i < r.quoteDepth; i++ {
		r.raw(esc("> "))
	}
	if r.indent > 0 {
		r.raw(strings.Repeat(" ", r.indent))
	}

	// Стили, закрытые переносом, открываются заново — но уже на этой строке и
	// после маркера. Не открылись из-за нехватки места — владение всё равно
	// остаётся за теми же фреймами, и снять их сможет только их владелец.
	for i := range r.frames {
		if r.frames[i].live {
			continue
		}
		if !r.raiseFrame(&r.frames[i]) {
			// Стиль не поместился на новой строке — показ ОБРЫВАЕТСЯ здесь.
			// Иначе профиль, обязанный рисовать жирный, писал бы следующую
			// строку без него: то самое «тег не влез, текст пошёл дальше», от
			// которого мы ушли, только на переоткрытии после переноса.
			r.cut()
			return
		}
		r.frames[i].live = true
	}
}

// breakLine переводит строку: закрывает теги, ставит маркер, открывает заново.
func (r *richRenderer) breakLine() {
	if r.policy.fullPre {
		// В общем блоке перенос строки — просто перенос: закрывать и открывать
		// нечего, всё тело лежит внутри одного тега. Прежде эта ветка
		// отсутствовала, и первый же перенос закрывал блок, а startLine его не
		// переоткрывал — тело вываливалось из тега целиком.
		r.seen++
		if r.raw("\n") {
			r.covered++
		}
		// Строка кончилась и здесь: приставки цитаты и списка печатаются в
		// общем блоке наравне с прочими профилями — без них цитата и список
		// слиплись бы в сплошной текст. Маркер строки startLine пропустит сам.
		r.atLineStart = true
		return
	}

	for i := len(r.frames) - 1; i >= 0; i-- {
		if r.frames[i].live {
			r.lowerFrame(r.frames[i])
			r.frames[i].live = false
		}
	}

	r.seen++
	if r.raw("\n") {
		r.covered++
	}
	r.atLineStart = true

	// Ни приставок строки, ни переоткрытия стилей здесь нет: и то и другое
	// делает startLine при первой записи в новую строку. В момент переноса
	// структура ещё прежняя — печать отсюда давала вложенному пункту отступ
	// внешнего уровня.
}

// blankLine — пустая строка тела, и она тоже получает маркер.
//
// Иначе подделка отделяется пустой строкой и оказывается зрительно оторванной
// от тела — а именно на зрительном отделении обман и держится.
func (r *richRenderer) blankLine() {
	r.breakLine()
	// Пустую строку никто не наполнит, поэтому приставки ей ставим сами:
	// лениво они бы так и не появились.
	r.startLine()
	r.breakLine()
}

// openTag заводит фрейм стиля и пытается его открыть.
//
// Возвращает дескриптор фрейма — им, и только им, этот стиль потом
// закрывается. Фрейм заводится и тогда, когда места не хватило: владение
// важнее физического тега, иначе закрытие уедет на чужой стиль.
func (r *richRenderer) openTag(tag string) int {
	if r.truncated {
		return -1
	}
	r.startLine()

	frame := tagFrame{id: r.takeFrameID(), tag: tag, open: "<" + tag + ">"}
	frame.live = r.raiseFrame(&frame)
	if !frame.live {
		// Места на тег нет — показ ОБРЫВАЕТСЯ здесь, а не продолжается тем же
		// текстом без оформления. Продолжение и было болезнью: решение
		// принималось по остатку предела, и лишняя руна включала дорогой тег,
		// отнимая у письма два десятка рун. Что рисовать, решает профиль;
		// предел решает только, докуда мы дошли.
		r.cut()
	}
	r.frames = append(r.frames, frame)
	return frame.id
}

// openLink открывает ссылку, если на неё хватает места.
//
// В отличие от стиля фрейм не заводится: ссылка живёт внутри одной строки —
// в адресе нет пробелов, переносу взяться неоткуда, — и держать её как
// владение незачем. Не хватило места — показ обрывается перед адресом:
// профиль, показывающий адрес текстом, отдельный, и выбирается по покрытию.
func (r *richRenderer) openLink(href string) int {
	if r.truncated {
		return -1
	}
	r.startLine()

	frame := tagFrame{id: r.takeFrameID(), tag: "a", open: `<a href="` + esc(href) + `">`}

	// Ссылка атомарна: открытие, ВЕСЬ видимый адрес и закрытие — либо обрыв
	// перед ней. Показать «h» со скрытой полной целью нельзя: человек видит
	// одну букву, а клик ведёт по всему адресу, которого он не читал.
	if runes(frame.open)+runes(esc(href))+runes("</a>") > r.avail() {
		r.cut()
		return -1
	}
	if !r.raiseFrame(&frame) {
		r.cut()
		return -1
	}
	frame.live = true
	r.frames = append(r.frames, frame)
	return frame.id
}

func (r *richRenderer) takeFrameID() int {
	r.nextFrameID++
	return r.nextFrameID
}

// frameAt — где в стеке лежит фрейм с этой самоличностью.
func (r *richRenderer) frameAt(id int) int {
	for i := len(r.frames) - 1; i >= 0; i-- {
		if r.frames[i].id == id {
			return i
		}
	}
	return -1
}

// live — открыт ли фрейм физически прямо сейчас.
func (r *richRenderer) live(handle int) bool {
	at := r.frameAt(handle)
	return at >= 0 && r.frames[at].live
}

// styles — рисует ли этот показ жирный и курсив.
//
// В общем блоке не рисует никогда: вложенных тегов там быть не может.
func (r *richRenderer) styles() bool {
	return r.policy.styles && !r.policy.fullPre
}

// raiseFrame физически открывает тег, если хватает места и на закрытие.
//
// Плюс руна: тег, внутри которого не поместится ни одного символа, открывать
// незачем. Открыть, не сумев закрыть, — худший из исходов: пост уходит с
// несбалансированной разметкой, и Telegram отвергает его целиком.
func (r *richRenderer) raiseFrame(frame *tagFrame) bool {
	closing := "</" + frame.tag + ">"
	if runes(frame.open)+runes(closing)+1 > r.avail() {
		return false
	}
	r.budget -= runes(frame.open)
	r.reserve += runes(closing)
	r.out.WriteString(frame.open)
	return true
}

// lowerFrame физически закрывает тег.
//
// Пишет мимо raw намеренно: место под это закрытие удержано в reserve с
// момента открытия, поэтому отказать здесь нельзя — отказ и означал бы
// несбалансированный вывод.
func (r *richRenderer) lowerFrame(frame tagFrame) {
	closing := "</" + frame.tag + ">"
	r.reserve -= runes(closing)
	r.budget -= runes(closing)
	r.out.WriteString(closing)
}

// closeFrame закрывает СВОЙ фрейм.
//
// Всё, что осталось открытым внутри него, закрывается заодно: незакрытый
// вложенный фрейм означал бы ошибку обхода, и молча оставить его открытым
// хуже, чем закрыть.
func (r *richRenderer) closeFrame(handle int) {
	at := r.frameAt(handle)
	if at < 0 {
		// Фрейма нет: либо не заводился, либо уже закрыт. Закрывать чужой на
		// его месте нельзя — ровно этим и был дефект.
		return
	}
	for len(r.frames) > at {
		r.dropFrame()
	}
}

func (r *richRenderer) dropFrame() {
	frame := r.frames[len(r.frames)-1]
	r.frames = r.frames[:len(r.frames)-1]
	if frame.live {
		r.lowerFrame(frame)
	}
}

// text пишет текст письма, экранируя его и соблюдая предел.
//
// Режет ВНУТРИ текста, а не отбрасывает узел целиком: тело из одного длинного
// абзаца иначе исчезло бы полностью.
func (r *richRenderer) text(s string) {
	r.textJoined(s, boundary{})
}

// joinsNext — идёт ли следующий видимый символ вплотную к этому узлу.
//
// Общий контракт для всех узлов, чей текст выходит наружу: лексема не
// обязана кончаться там, где кончается узел, и хвост за границей должен быть
// обезврежен тоже.
// boundary — что стоит сразу за узлом.
//
// Одного признака «слитно» мало, и одной соседней руны тоже. Опасность
// появляется не у символа, а у ЛЕКСЕМЫ: «курсив» + «;» не образует ничего, а
// «https» + «://example.com» образует адрес. Поэтому граница несёт видимое
// продолжение до конца слова — по нему и решается, обезвреживать ли хвост.
type boundary struct {
	joined bool
	// tail — видимое продолжение лексемы за границей узла.
	tail string
	// opaque — продолжение известно не полностью: дальше стоит узел, о
	// показе которого мы не знаем, либо хвост длиннее предела. Склейку не
	// проверить, поэтому считаем её опасной.
	opaque bool
}

func (r *richRenderer) boundaryAfter(n ast.Node, source []byte) boundary {
	next, ok := nextVisibleRune(n, source)
	if !ok || unicode.IsSpace(next) {
		return boundary{}
	}
	tail, known := nextVisibleLexeme(n, source)
	return boundary{joined: true, tail: tail, opaque: !known}
}

// joinedDangerous — образует ли склейка с соседом опасную лексему.
//
// Здесь исправлена ошибка первого выпуска показа. Прежнее правило спрашивало
// про ОДИН соседний символ: «может ли он продолжать лексему». Ответ почти
// всегда «может» — и обычное «это **важно**, потому что…» уходило в
// моноширинный вид целиком, вместе с потерей жирного: Telegram не накладывает
// стиль на code. Дефект дошёл до боевого узла и был виден глазами в первом же
// письме.
//
// Вопрос был поставлен не о том. Обезвреживать нужно не потому, что сосед
// стоит вплотную, а потому, что ВМЕСТЕ они образуют то, что Telegram сделает
// активным. Обе части в этот момент уже на руках, склеить их и спросить
// dangerousLexeme — прямая проверка вместо догадки о символе.
//
// Что сохраняется от прежнего правила: если сам кусок опасен или продолжает
// опасный, хвост уходит под обёртку без всяких склеек — там мы лексему целиком
// не видим, а Telegram видит.
//
// Урок, который стоит держать при следующей правке: проверка «символ плюс
// буква» ничего не доказывает про символ. «example.com.x» не продолжилось, а
// «example.com.org» продолжится — та же точка, разный хвост. Утверждения о
// символе требуют доказательства для бесконечного множества хвостов;
// утверждение о конкретной склейке проверяется одним вызовом.
func joinedDangerous(кусок string, край boundary) bool {
	if край.opaque {
		return true
	}
	return dangerousLexeme(кусок + край.tail)
}

// textJoined пишет текст письма, зная, продолжается ли последняя лексема за
// границей этого узла.
func (r *richRenderer) textJoined(s string, край boundary) {
	if s == "" {
		return
	}
	r.startLine()

	// Перевод строки внутри одного узла разбором обычно не оставляется, но
	// проглотить его молча нельзя: склеенная строка потеряла бы маркер, если
	// такой узел когда-нибудь появится.
	for i, part := range strings.Split(s, "\n") {
		if i > 0 {
			r.breakLine()
		}
		if part != "" {
			край := край
			if i < len(strings.Split(s, "\n"))-1 {
				край = boundary{}
			}
			r.writePayload(part, край)
		}
	}
}

// writePayload выводит текст письма, обезвреживая опасные лексемы.
//
// Лексема, которую Telegram способен сделать активной, уходит в моноширинный
// вид: внутри code он не распознаёт ничего. Видимый текст при этом не
// меняется ни на руну — ни вставок, ни замен: человек должен прочесть и
// скопировать ровно то, что написал отправитель.
func (r *richRenderer) writePayload(s string, край boundary) {
	if r.protected > 0 || r.policy.fullPre {
		// Здесь подавлять нечего: авторский блок кода и общий блок глушат
		// распознавание сами, а внутри нашей ссылки стоит проверенный адрес.
		r.writeEscaped(s)
		r.pending = false
		return
	}

	куски := lexemes(s)
	for i, кусок := range куски {
		if isSpaceLexeme(кусок) {
			r.writeEscaped(кусок)
			r.pending = false
			continue
		}

		// Опасна сама лексема, или она продолжает опасную с прошлого узла,
		// или продолжится за границей этого. В двух последних случаях мы не
		// видим её целиком — и потому считаем опасной: увидеть её целиком
		// может Telegram, а он смотрит на готовую строку.
		продолжение := i == 0 && r.pending
		опасен := dangerousLexeme(кусок) || продолжение

		// Хвост за границей узла уходит под обёртку, если ему есть что
		// продолжать: либо этот кусок уже опасен, либо опасна склейка его с
		// соседним словом. Одного соседства мало — «курсив» + «;» безвредно.
		продолжится := i == len(куски)-1 && край.joined &&
			(опасен || joinedDangerous(кусок, край))

		if опасен || продолжится {
			r.writeSuppressed(кусок)
		} else {
			r.writeEscaped(кусок)
		}
		r.pending = продолжится
	}
}

func isSpaceLexeme(s string) bool {
	for _, r := range s {
		return unicode.IsSpace(r)
	}
	return false
}

// writeSuppressed заворачивает лексему в моноширинный вид целиком.
//
// Атомарно: либо открытие, вся лексема и закрытие, либо показ обрывается
// перед ней. Половина лексемы снаружи тега — это голый хвост, который
// Telegram распознает и сделает активным; лучше не показать ничего.
func (r *richRenderer) writeSuppressed(lexeme string) {
	const open, closing = "<code>", "</code>"

	if r.truncated {
		// Поток всё равно считаем: полнота меряется относительно письма.
		r.seen += runes(lexeme)
		return
	}

	// Строку начинаем ДО расчёта: маркер, приставки цитаты и списка и
	// переоткрытие стилей тоже занимают место. Считая стоимость до них, мы
	// получали бы запас, которого на деле нет, — и лексема выходила бы
	// обрезанной внутри обёртки, то есть половиной.
	r.startLine()

	if runes(open)+runes(esc(lexeme))+runes(closing) > r.avail() {
		r.cut()
		r.seen += runes(lexeme)
		return
	}

	code := r.openTag("code")
	if !r.live(code) {
		r.closeFrame(code)
		r.seen += runes(lexeme)
		return
	}
	r.protected++
	r.writeEscaped(lexeme)
	r.protected--
	r.closeFrame(code)
}

func (r *richRenderer) writeEscaped(s string) {
	// Встреченное считается всегда, даже после обрыва: полная длина потока
	// нужна, чтобы понять, показано ли письмо целиком.
	r.seen += runes(s)
	if r.truncated || s == "" {
		return
	}

	written := esc(s)
	if runes(written) <= r.avail() {
		r.budget -= runes(written)
		r.out.WriteString(written)
		r.covered += runes(s)
		return
	}

	// Влезает не всё: пишем по руне, пока есть место. Стоимость считается в
	// том виде, в каком руна уйдёт наружу, — одна угловая скобка занимает
	// четыре руны, — а покрытие в рунах письма.
	for _, rn := range s {
		piece := esc(string(rn))
		if runes(piece) > r.avail() {
			break
		}
		r.budget -= runes(piece)
		r.out.WriteString(piece)
		r.covered++
	}
	r.cut()
}

// walk обходит дерево и пишет разметку.
//
// Теги ставит ТОЛЬКО он, из закрытого списка; текст письма выходит наружу
// исключительно через esc(). Поэтому подделка тегов из тела невозможна, а
// незнакомый узел вырождается в текст, а не в разметку.
func (r *richRenderer) walk(node ast.Node, source []byte) {
	r.render(node, source)
}

func (r *richRenderer) render(n ast.Node, source []byte) {
	switch node := n.(type) {
	case *ast.Document:
		r.renderBlocks(node, source)

	case *ast.Paragraph, *ast.TextBlock:
		r.renderChildren(n, source)

	case *ast.Heading:
		// Заголовков в Telegram нет: показываем жирной строкой.
		if !r.styles() {
			r.renderChildren(node, source)
			return
		}
		heading := r.openTag("b")
		r.renderChildren(node, source)
		r.closeFrame(heading)

	case *ast.FencedCodeBlock, *ast.CodeBlock:
		r.writeCodeBlock(n, source)

	case *ast.Blockquote:
		// Вложенные цитаты Telegram запрещает, поэтому цитата — текстовая
		// приставка строки, а не сущность.
		r.quoteDepth++
		r.startLine()
		r.renderBlocks(node, source)
		r.quoteDepth--

	case *ast.List:
		r.renderLines(node, source)

	case *ast.ListItem:
		r.startLine()
		// Буллет — приставка строки, как «> » и отступ: в покрытие не входит,
		// но печатается всеми профилями, включая общий блок.
		r.raw("• ")

		// Дальше строки этого пункта идут с отступом в ширину буллета —
		// включая вложенные списки, которые тем самым получают свой уровень.
		outer := r.indent
		r.indent += runes("• ")
		r.renderLines(node, source)
		r.indent = outer

	case *ast.Emphasis:
		if !r.styles() {
			r.renderChildren(node, source)
			return
		}
		tag := "i"
		if node.Level == 2 {
			tag = "b"
		}
		emphasis := r.openTag(tag)
		r.renderChildren(node, source)
		r.closeFrame(emphasis)

	case *ast.CodeSpan:
		if !r.policy.authorCode || r.policy.fullPre {
			// Свой тег профиль не рисует, значит и защиты нет: содержимое
			// проходит через подавитель как обычный текст письма.
			r.renderChildren(node, source)
			return
		}
		code := r.openTag("code")
		r.protected++
		r.renderChildren(node, source)
		r.protected--
		r.closeFrame(code)

	case *ast.Link:
		// Ссылкой не становится: скрытая цель — самый частый обман, а правило
		// «показывать цель, если текст похож на адрес» пропускает
		// «нажмите здесь» со ссылкой на что угодно.
		r.renderChildren(node, source)
		r.text(" (" + string(node.Destination) + ")")

	case *ast.AutoLink:
		r.writeAutoLink(node, source)

	case *ast.RawHTML:
		// Сырой HTML из тела — всегда текст, и лексема может продолжаться за
		// его границей: «<b>@evil.example» приходит двумя узлами, а Telegram
		// смотрит на готовую строку.
		for i := 0; i < node.Segments.Len(); i++ {
			segment := node.Segments.At(i)

			// Продолжение за узлом относится только к последнему куску:
			// между сегментами одного узла разрыва нет вовсе.
			край := boundary{}
			if i == node.Segments.Len()-1 {
				край = r.boundaryAfter(node, source)
			}
			r.textJoined(string(segment.Value(source)), край)
		}

	case *ast.HTMLBlock:
		r.writeLinesAsText(node, source)

	case *ast.Text:
		// Слитно ли идёт следующий узел: если да, лексема не кончилась на
		// границе этого, и её хвост придётся обезвредить тоже.
		край := boundary{}
		if !node.SoftLineBreak() && !node.HardLineBreak() {
			// Перенос строки — разрыв на экране: лексема за ним не
			// продолжается, как бы близко ни стоял следующий узел.
			край = r.boundaryAfter(node, source)
		}
		r.textJoined(string(node.Segment.Value(source)), край)
		if node.SoftLineBreak() || node.HardLineBreak() {
			r.breakLine()
		}

	case *ast.String:
		r.textJoined(string(node.Value), r.boundaryAfter(node, source))

	default:
		r.renderChildren(n, source)
	}
}

// renderBlocks обходит блочные узлы, разделяя их пустой строкой с маркером.
func (r *richRenderer) renderBlocks(n ast.Node, source []byte) {
	r.renderSeparated(n, source, r.blankLine)
}

// renderLines разделяет детей переводом строки: так идут пункты списка, между
// которыми пустая строка была бы вымыслом — в теле её не было.
func (r *richRenderer) renderLines(n ast.Node, source []byte) {
	r.renderSeparated(n, source, r.breakLine)
}

func (r *richRenderer) renderSeparated(n ast.Node, source []byte, sep func()) {
	first := true
	for child := n.FirstChild(); child != nil; child = child.NextSibling() {
		if !first {
			sep()
		}
		first = false
		r.render(child, source)
	}
}

func (r *richRenderer) renderChildren(n ast.Node, source []byte) {
	for child := n.FirstChild(); child != nil; child = child.NextSibling() {
		r.render(child, source)
	}
}

// writeCodeBlock выводит блок кода.
//
// Блок кода — единственная зона без маркера: он попал бы в буфер при
// копировании и сломал код. Блок отличим сам и шапку не имитирует.
func (r *richRenderer) writeCodeBlock(n ast.Node, source []byte) {
	if !r.policy.authorCode || r.policy.fullPre {
		// Профиль показывает код обычными строками. В общем блоке иначе и
		// нельзя: блок внутри блока Telegram не примет.
		r.writeLinesAsText(n, source)
		return
	}

	pre := r.openTag("pre")
	if !r.live(pre) {
		// Места на тег не хватило — показ уже оборван (openTag зовёт cut).
		// Показывать код текстом здесь нельзя: строки внутри блока идут без
		// маркера, и выпавший из тега текст стал бы строками без границы
		// доверия. Обычными строками код показывает ДРУГОЙ профиль.
		//
		// Обойти строки всё равно надо: записи не будет, но поток досчитается.
		// Без этого полная длина потока зависела бы от того, где кандидат
		// оборвался, — и кандидаты сравнивались бы по разным линейкам. Хуже
		// того, кандидат с нулём в числителе и нуле в знаменателе выглядел бы
		// показавшим всё.
		r.closeFrame(pre)
		r.writeLinesAsText(n, source)
		return
	}

	r.protected++
	defer func() { r.protected-- }()

	for i, line := range codeLines(n, source) {
		if i > 0 {
			// Внутри блока перевод строки — просто перевод: ни маркера, ни
			// приставок там нет. Но в поток он входит, и потому считается.
			r.seen++
			if r.raw("\n") {
				r.covered++
			}
		}
		r.writeEscaped(line)
	}
	r.closeFrame(pre)
	r.atLineStart = true
}

func (r *richRenderer) writeLinesAsText(n ast.Node, source []byte) {
	for i, line := range codeLines(n, source) {
		if i > 0 {
			r.breakLine()
		}
		r.text(line)
	}
}

// codeLines — строки блока кода БЕЗ терминального перевода.
//
// Общая для всех профилей: раньше блок со своим тегом писал сегменты как
// есть, вместе с переводом в конце последней строки, а построчный показ его
// отбрасывал. Итог — разные длины канонического потока у разных профилей, то
// есть кандидаты сравнивались по разным линейкам. Перевод между строками
// ставит тот, кто печатает, — он один и тот же у всех.
func codeLines(n ast.Node, source []byte) []string {
	lines := n.Lines()

	out := make([]string, 0, lines.Len())
	for i := 0; i < lines.Len(); i++ {
		segment := lines.At(i)
		out = append(out, strings.TrimRight(string(segment.Value(source)), "\n"))
	}
	return out
}

// writeAutoLink делает голый адрес ссылкой, если он прошёл проверку.
//
// Проверяется ЛЕКСЕМА ЦЕЛИКОМ, а не то, что осталось после разбора. Linkify
// обрывает адрес на «собаке»: из «https://github.com@зло.example» он делает
// ссылку на github.com и текст «@зло.example» следом. Человек видит строку
// целиком и вправе думать, что клик ведёт туда, — а ведёт в другое место.
func (r *richRenderer) writeAutoLink(node *ast.AutoLink, source []byte) {
	// Видимый текст берётся из ЛЕЙБЛА, цель — из URL, и они обязаны совпасть
	// дословно.
	//
	// Linkify достраивает схему: «www.example.com» приходит с URL
	// «http://www.example.com», и раньше мы печатали URL — то есть меняли
	// текст чужого письма. Отправитель написал одно, человек читал другое.
	// Нашла это живая матрица, а не тесты: они сверяли безопасность, а не
	// дословность.
	//
	// Достроенную схему нельзя ни печатать, ни прятать в href: печатать —
	// искажение, прятать — скрытая цель, да ещё и выбранная за автора, причём
	// небезопасная. Поэтому при любом расхождении ссылки просто нет: текст
	// выходит как написан, а домен завернёт подавитель.
	visible := string(node.Label(source))
	raw := string(node.URL(source))

	// Лексема может продолжаться за узлом ссылки: «https://example.com/путь»
	// приходит двумя узлами — разбор берёт в адрес только ASCII, а
	// кириллический хвост остаётся текстом. Не передав продолжение дальше, мы
	// оставляли «путь» голым рядом с обёрнутым адресом.
	край := r.boundaryAfter(node, source)

	if visible != raw {
		r.textJoined(visible, край)
		return
	}

	if !lexemeEndsHere(node, source) {
		// Разбор оборвал лексему на полпути. Ссылки не делаем вовсе: остаток
		// выйдет наружу своим чередом, обычным текстом, и человек увидит
		// исходный кусок целиком и без клика.
		r.textJoined(raw, край)
		return
	}

	if !allowedURL(raw) {
		r.textJoined(raw, край)
		return
	}

	if !r.policy.links || r.policy.fullPre {
		// Профиль ссылок не рисует: адрес выходит видимым текстом. Кликнуть
		// по нему человек не сможет, зато прочтёт целиком — и это ровно то,
		// чем ссылка дороже всего прочего: адрес в href дублирует лексему.
		r.textJoined(raw, край)
		return
	}

	link := r.openLink(raw)
	if link < 0 {
		// Места не хватило, и показ уже оборван — openLink зовёт cut. Текст
		// пишется всё равно: записи не будет, но встреченные руны досчитаются
		// в поток, а по нему меряется полнота всех кандидатов.
		r.textJoined(raw, край)
		return
	}
	r.protected++
	r.text(raw)
	r.protected--
	r.closeFrame(link)
}

// lexemeEndsHere — виден ли на экране разрыв сразу за адресом.
//
// Linkify обрывает адрес на «собаке»: из «https://github.com@зло.example» он
// делает ссылку на github.com и текст «@зло.example» следом. Человек читает
// строку целиком и вправе думать, что клик ведёт по всему адресу, — а ведёт в
// другое место. Это не косметика, а подмена цели.
//
// Вопрос, который здесь задаётся, — «что человек увидит сразу за ссылкой», и
// это свойство ПОРЯДКА ДОКУМЕНТА, а не родства узлов. Прежняя версия
// спрашивала про соседа по дереву и закрывала дыру наполовину: у
// «*https://github.com*@evil.example» ссылка — последний ребёнок выделения,
// соседа у неё нет вовсе, а хвост прилегает снаружи. Перечислять типы узлов
// бесполезно ровно по той же причине, по которой не годится рукописный список
// переводов строк: список чужой, его пополняет goldmark.
func lexemeEndsHere(node *ast.AutoLink, source []byte) bool {
	next, ok := nextVisibleRune(node, source)
	if !ok {
		// Текст кончился. Разрыв виден именно потому, что дальше ничего нет,
		// и это разрешается явным условием, а не молчанием: иначе ссылка в
		// конце курсива переставала бы быть ссылкой без всякой причины.
		return true
	}
	return isLexemeTerminator(next)
}

// nextVisibleRune — первый символ, который рендерер выведет после узла.
//
// Идёт по документу, а не по детям: сперва вправо по соседям, затем вверх к
// родителю и снова вправо, пока не кончится документ.
func nextVisibleRune(n ast.Node, source []byte) (rune, bool) {
	for cur := n; cur != nil && cur.Kind() != ast.KindDocument; cur = cur.Parent() {
		for sib := cur.NextSibling(); sib != nil; sib = sib.NextSibling() {
			if r, ok := firstVisibleRune(sib, source); ok {
				return r, true
			}
		}
	}
	return 0, false
}

// joinedTailLimit — сколько рун продолжения учитывать в склейке.
//
// Предел нужен не ради скорости: без него одно длинное слово заставляло бы
// обходить документ до конца на каждой границе. Обрыв решается в безопасную
// сторону — не увидев лексему целиком, обезвреживаем.
//
// Считается в РУНАХ, и это не мелочь: по байтам тот же предел наступал бы для
// кириллицы вдвое раньше, чем для латиницы, и письма на русском получали бы
// лишние обёртки там, где английские не получают. Ровно тот класс порчи вида,
// который правится этим коммитом.
const joinedTailLimit = 256

// lexemeTail — накопитель видимого продолжения с учётом предела.
//
// Счётчик рун ведётся явно, а не пересчитывается из накопленной строки:
// пересчёт на каждой руне дал бы квадрат от длины хвоста.
type lexemeTail struct {
	text  strings.Builder
	runes int
}

// writeRune дописывает руну; ложь означает, что предел исчерпан.
func (t *lexemeTail) writeRune(r rune) bool {
	if t.runes >= joinedTailLimit {
		return false
	}
	t.text.WriteRune(r)
	t.runes++
	return true
}

func (t *lexemeTail) String() string {
	return t.text.String()
}

// nextVisibleLexeme — видимое продолжение лексемы сразу за узлом.
//
// Идёт по документу так же, как nextVisibleRune: вправо по соседям, затем
// вверх к родителю. Останавливается на первом пробеле — дальше уже другое
// слово, и к склейке оно отношения не имеет.
//
// Второе значение — «продолжение известно целиком». Ложь означает, что
// впереди узел с неизвестным показом или слишком длинный хвост: склейку
// проверить нечем, и решать придётся консервативно.
func nextVisibleLexeme(n ast.Node, source []byte) (string, bool) {
	var tail lexemeTail
	for cur := n; cur != nil && cur.Kind() != ast.KindDocument; cur = cur.Parent() {
		for sib := cur.NextSibling(); sib != nil; sib = sib.NextSibling() {
			done, known := appendVisiblePrefix(&tail, sib, source)
			if !known {
				return tail.String(), false
			}
			if done {
				return tail.String(), true
			}
		}
	}
	// Документ кончился: продолжения нет, и это известно точно.
	return tail.String(), true
}

// appendVisiblePrefix дописывает видимый текст узла до конца лексемы.
//
// Разбор узлов повторяет firstVisibleRune намеренно: спрашивается то же
// самое — что человек увидит, — и расхождение между этими двумя ответами было
// бы дырой, а не экономией.
func appendVisiblePrefix(tail *lexemeTail, n ast.Node, source []byte) (done, known bool) {
	switch node := n.(type) {
	case *ast.Text:
		if value := node.Segment.Value(source); len(value) > 0 {
			return appendUntilSpace(tail, string(value))
		}
		if node.SoftLineBreak() || node.HardLineBreak() {
			// Перенос строки кончает лексему так же, как пробел.
			return true, true
		}
		return false, true

	case *ast.String:
		if len(node.Value) > 0 {
			return appendUntilSpace(tail, string(node.Value))
		}
		return false, true

	case *ast.RawHTML:
		// Сырой HTML мы печатаем текстом — человек увидит его как есть.
		for i := 0; i < node.Segments.Len(); i++ {
			segment := node.Segments.At(i)
			if done, known := appendUntilSpace(tail, string(segment.Value(source))); done || !known {
				return done, known
			}
		}
		return false, true

	case *ast.AutoLink:
		if url := node.URL(source); len(url) > 0 {
			return appendUntilSpace(tail, string(url))
		}
		return false, true
	}

	if n.Type() == ast.TypeBlock {
		// Новый блок начинается с новой строки — лексема кончилась.
		return true, true
	}

	if n.FirstChild() == nil {
		// Лист не из знакомых: чем он обернётся на экране, мы не знаем.
		return false, false
	}

	for child := n.FirstChild(); child != nil; child = child.NextSibling() {
		done, known := appendVisiblePrefix(tail, child, source)
		if !known {
			return false, false
		}
		if done {
			return true, true
		}
	}
	return false, true
}

// appendUntilSpace дописывает руны до первого пробела.
//
// done — лексема кончилась внутри этого куска; known — ложь, когда хвост
// упёрся в предел и остаток остался невидимым.
func appendUntilSpace(tail *lexemeTail, s string) (done, known bool) {
	for _, r := range s {
		if unicode.IsSpace(r) {
			return true, true
		}
		if !tail.writeRune(r) {
			return false, false
		}
	}
	return false, true
}

// unknownVisible — символ для узла, о котором мы не знаем, что он покажет.
//
// Терминатором не является, поэтому ссылка не делается: не сумев доказать
// разрыв, отказываем. Ошибка в эту сторону стоит некликабельного адреса,
// ошибка в другую — клика не туда, куда написано.
const unknownVisible = '\uFFFD'

// firstVisibleRune — первый символ, который узел покажет человеку.
//
// Второе значение — «ответ найден»: узел может не показать ничего (пустой
// текст, разметка выделения), и тогда смотреть надо дальше.
func firstVisibleRune(n ast.Node, source []byte) (rune, bool) {
	switch node := n.(type) {
	case *ast.Text:
		if value := node.Segment.Value(source); len(value) > 0 {
			return firstRune(value), true
		}
		if node.SoftLineBreak() || node.HardLineBreak() {
			// Перенос строки виден как разрыв, и этого достаточно.
			return '\n', true
		}
		return 0, false

	case *ast.String:
		if len(node.Value) > 0 {
			return firstRune(node.Value), true
		}
		return 0, false

	case *ast.RawHTML:
		// Сырой HTML мы печатаем текстом, значит человек увидит «<».
		if node.Segments.Len() > 0 {
			segment := node.Segments.At(0)
			return firstRune(segment.Value(source)), true
		}
		return 0, false

	case *ast.AutoLink:
		if url := node.URL(source); len(url) > 0 {
			return firstRune(url), true
		}
		return 0, false
	}

	if n.Type() == ast.TypeBlock {
		// Новый блок начинается с новой строки — разрыв виден.
		return '\n', true
	}

	for child := n.FirstChild(); child != nil; child = child.NextSibling() {
		if r, ok := firstVisibleRune(child, source); ok {
			return r, true
		}
	}

	if n.FirstChild() == nil {
		// Узел без детей и не из знакомых: чем он обернётся на экране, мы не
		// знаем. Считаем, что чем-то видимым.
		return unknownVisible, true
	}
	return 0, false
}

func firstRune(b []byte) rune {
	for _, r := range string(b) {
		return r
	}
	return unknownVisible
}

// isLexemeTerminator — символ, на котором слово кончается на глаз.
//
// Пробелы и та завершающая пунктуация, которую Linkify сам не берёт в адрес.
// «Собаки» здесь нет намеренно: именно она превращает написанное в чужой хост.
//
// Звёздочки и обратные кавычки сюда не входят и входить не должны: на экране
// их нет, они разметка. Спрашивать надо о том, что человек увидит.
func isLexemeTerminator(r rune) bool {
	if unicode.IsSpace(r) {
		return true
	}
	return strings.ContainsRune(`.,;:!?)]}"'«»…`, r)
}

// allowedURL — адрес, который можно сделать ссылкой.
//
// Почта сюда тоже приходит — Linkify отдаёт её автоссылкой — и отсеивается
// первым же условием: схемы у неё нет. Отдельной ветки для почты нет
// намеренно: она вела бы к тому же результату, а неразличимую поведением
// ветку нельзя ни проверить тестом, ни поддерживать честно.
//
// Схема обязана быть явной и известной: esc её не трогает вовсе, поэтому белый
// список здесь — единственная защита. Схема tg:// умеет открывать внутренние
// экраны Telegram, javascript: говорит сам за себя.
//
// Не-ASCII хост остаётся текстом: показ Unicode-цели не спасает от омоглифов
// (латинское и кириллическое «а» неразличимы), а punycode тянет отдельную
// политику имён.
func allowedURL(raw string) bool {
	parsed, err := url.Parse(raw)
	if err != nil {
		return false
	}
	if parsed.Scheme != "http" && parsed.Scheme != "https" {
		return false
	}
	if parsed.Hostname() == "" {
		// Именно Hostname, а не Host: у «http://:80» хост состоит из одного
		// порта, и Host непустой, хотя адрес не ведёт никуда.
		return false
	}
	if parsed.User != nil {
		// Логин в адресе — способ показать один хост, а увести на другой.
		//
		// Здесь закрывается ровно ASCII-случай: «https://github.com@evil.example»
		// Linkify отдаёт одной лексемой, разбор видит userinfo, и мы
		// отказываем. Случай «https://github.com@зло.example» сюда НЕ доходит:
		// не-ASCII хвост Linkify в адрес не берёт вовсе, лексему обрывает, и
		// его ловит проверка границы (lexemeEndsHere). Механизма два, они
		// закрывают разные вводы — убрав один, второй случай потеряешь молча.
		return false
	}
	for _, r := range parsed.Hostname() {
		if r > unicode.MaxASCII {
			return false
		}
	}
	return true
}
