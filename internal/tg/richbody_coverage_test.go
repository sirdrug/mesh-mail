// Общий блок безопасен сам по себе.
//
// Он больше не отдельное поле результата — аварийный повтор при отказе
// Telegram делает клиент, одинаково для всех сообщений. Здесь это обычный
// пятый кандидат, и проверяется он напрямую: маркеров нет, всё тело внутри
// одного блока, подавление даёт сам блок.
func TestОбщийБлокБезопасенСамПоСебе(t *testing.T) {
	тела := []string{
		"короткое письмо",
		"**жирный** и *курсив* и https://example.com/doc",
		"```\nкод один\nкод два\n```",
		"> цитата\n> вторая\n\n- пункт\n  - вложенный",
	}

	for _, body := range тела {
		t.Run(body, func(t *testing.T) {
			source, cutInput := boundInput(body)

			for _, budget := range []int{20, 60, 200, 4000} {
				сессия := &renderSession{doc: parseSource(source), source: source}
				got := сессия.finalize(budget, profiles[len(profiles)-1], cutInput)

				requireWithinBudget(t, got.html, budget)
				requireBalanced(t, got.html)
				if strings.Contains(got.html, LineMarker) {
					t.Errorf("предел %d: в общем блоке маркер строки: %q", budget, got.html)
				}
				if got.covered > 0 && !strings.HasPrefix(got.html, "<pre>") {
					t.Errorf("предел %d: текст показан вне блока: %q", budget, got.html)
				}
			}
		})
	}
}

// Структурные приставки видны и в общем блоке.
//
// Они не входят в покрытие — это служебное, — но выводятся всеми профилями:
// без «> » и буллетов цитата и список в моноширинном блоке слиплись бы в
// сплошной текст, и запасной показ стал бы хуже читаем, чем нынешний боевой.
func TestОбщийБлокСохраняетСтруктуру(t *testing.T) {
	source, cutInput := boundInput("> цитата\n> вторая\n\n- пункт\n  - вложенный")
	got := (&renderSession{doc: parseSource(source), source: source}).
		finalize(4000, profiles[len(profiles)-1], cutInput)

	for _, кусок := range []string{"&gt; цитата", "&gt; вторая", "• пункт", "  • вложенный"} {
		if !strings.Contains(got.html, кусок) {
			t.Errorf("в общем блоке нет %q: %q", кусок, got.html)
		}
	}
}

// Полная длина потока одна для всех профилей.
//
// По ней меряется полнота показа, значит она обязана быть общей линейкой.
// Разъезжалась она дважды и по-разному: блок кода со своим тегом считал
// терминальный перевод строки, а построчный показ его отбрасывал; и кандидат,
// оборвавшийся на теге, не обходил строки вовсе — у него выходило «ноль из
// нуля», то есть «показал всё».
func TestПолнаяДлинаПотокаОдинаковаУПрофилей(t *testing.T) {
	тела := map[string]string{
		"блок кода":        "```\nкод один\nкод два\n```",
		"блок с отступом":  "    отступом один\n    отступом два",
		"цитата и список":  "> цитата\n> вторая\n\n- пункт\n  - вложенный",
		"ссылки":           "смотри https://example.com/doc и [текст](https://x.example) тут",
		"смешанное":        "# заголовок\n\n**жирный** и `код`\n\n```\nблок\nкода\n```\n\n> цитата",
		"пустое":           "",
		"одна строка кода": "```\nкод\n```",
	}

	for имя, body := range тела {
		t.Run(имя, func(t *testing.T) {
			source, cutInput := boundInput(body)

			for _, budget := range []int{1, 5, 12, 20, 60, 200, 4000} {
				эталон := -1
				for _, p := range profiles {
					сессия := &renderSession{doc: parseSource(source), source: source}
					got := сессия.finalize(budget, p, cutInput)

					if эталон < 0 {
						эталон = got.total
						continue
					}
					if got.total != эталон {
						t.Fatalf("предел %d: у %q поток %d, а у первого профиля %d",
							budget, p.name, got.total, эталон)
					}
				}
			}
		})
	}
}

// Стиль, не переоткрывшийся после переноса, обрывает показ.
//
// Профиль обязан рисовать жирный — значит текст без жирного он выдать не
// может. Иначе это то же «тег не влез, текст пошёл дальше», от которого мы
// ушли, только на переоткрытии: первая строка выходит жирной, вторая —
// обычной, и предел снова решает за оформление.
func TestНеудачноеПереоткрытиеОбрываетПоказ(t *testing.T) {
	source, cutInput := boundInput("**жирный текст\nвторая строка**")

	for budget := 1; budget <= 80; budget++ {
		сессия := &renderSession{doc: parseSource(source), source: source}
		got := сессия.finalize(budget, profiles[0], cutInput)

		for _, line := range strings.Split(got.html, "\n") {
			for _, симв := range styleOf(line) {
				if симв.ch == '│' || симв.ch == ' ' || симв.ch == []rune(TruncationMark)[0] {
					continue
				}
				if !hasTag(симв.tags, "b") {
					t.Fatalf("предел %d: символ %q вышел из-под жирного: %q",
						budget, string(симв.ch), got.html)
				}
			}
		}
	}
}

// показПрофиля — готовый показ одного профиля при данном пределе.
func показПрофиля(body string, budget int, p profile) candidate {
	source, cutInput := boundInput(body)
	return (&renderSession{doc: parseSource(source), source: source}).finalize(budget, p, cutInput)
}

// Видимого текста при большем пределе не становится меньше.
//
// Свойство проверяется ВНУТРИ каждого профиля. Между профилями видимый текст
// сравнивать нельзя: служебные приставки у них разные — общий блок не печатает
// маркер строки, остальные печатают, — и разница в приставках не имеет
// отношения к тому, сколько письма дошло до человека. Итог выбора сравнивается
// отдельно, по счётчику покрытия.
func TestПокрытиеНеУбываетВнутриПрофиля(t *testing.T) {
	for имя, body := range coverageBodies {
		t.Run(имя, func(t *testing.T) {
			for _, p := range profiles {
				прежнее := -1
				for budget := 1; budget <= 200; budget++ {
					got := показПрофиля(body, budget, p)

					requireWithinBudget(t, got.html, budget)
					requireBalanced(t, got.html)

					if got.covered < прежнее {
						t.Fatalf("профиль %s, предел %d показал %d рун письма, а %d показывал %d: %q",
							p.name, budget, got.covered, budget-1, прежнее, got.html)
					}
					прежнее = got.covered
				}
			}
		})
	}
}

// Покрытие ИТОГА тоже не убывает с ростом предела.
//
// Считается счётчиком, а не оракулом: покрытие не зависит от того, какие
// приставки печатает выбранный профиль, и потому сравнимо между профилями.
func TestПокрытиеИтогаНеУбывает(t *testing.T) {
	for имя, body := range coverageBodies {
		t.Run(имя, func(t *testing.T) {
			source, cutInput := boundInput(body)

			прежнее := -1
			for budget := 1; budget <= 200; budget++ {
				got := (&renderSession{doc: parseSource(source), source: source}).choose(budget, cutInput)

				if got.covered < прежнее {
					t.Fatalf("предел %d показал %d рун письма, а %d показывал %d: %q",
						budget, got.covered, budget-1, прежнее, got.html)
				}
				прежнее = got.covered
			}
		})
	}
}

// Знак обрезки и признак неполноты сходятся с покрытием.
//
// Проверяется у ВЫБРАННОГО кандидата и против счётчика, а не против обратного
// разбора HTML: восстановить канонический поток из готовой разметки нельзя —
// в общем блоке структурная приставка «> » и буквальное начало строки кода
// неотличимы по сериализации в принципе. Всякая эвристика там ждёт своей
// фикстуры, и сегодня дождалась дважды.
//
// Сам счётчик удостоверяется отдельно, числами, посчитанными руками, —
// см. TestПокрытиеСходитсяСРучнымСчётом.
func TestЗнакОбрезкиСходитсяСПокрытием(t *testing.T) {
	for имя, body := range coverageBodies {
		t.Run(имя, func(t *testing.T) {
			source, cutInput := boundInput(body)

			for budget := 1; budget <= 200; budget++ {
				got := (&renderSession{doc: parseSource(source), source: source}).choose(budget, cutInput)

				неполон := got.covered < got.total
				if got.truncated != неполон {
					t.Errorf("предел %d: показано %d из %d, а обрезка объявлена как %v: %q",
						budget, got.covered, got.total, got.truncated, got.html)
				}
				if неполон && got.html != "" && !strings.HasSuffix(got.html, TruncationMark) {
					t.Errorf("предел %d: показано не всё, а знака нет: %q", budget, got.html)
				}
				if !неполон && strings.Contains(got.html, TruncationMark) {
					t.Errorf("предел %d: показано всё, а знак стоит: %q", budget, got.html)
				}
			}
		})
	}
}

// Пределы, на которых письмо обязано быть показано целиком.
//
// Полнота меряется счётчиком покрытия: он не зависит от приставок выбранного
// профиля, поэтому сравним с полной длиной потока напрямую.
func TestНаЭтихПределахПисьмоЦело(t *testing.T) {
	случаи := []struct {
		body   string
		budget int
	}{
		// Отказ от ссылки: адрес выходит текстом — и тогда его обязана
		// прикрыть обёртка подавителя, потому что голый адрес Telegram
		// распознаёт сам. Обёртка стоит тринадцать рун, поэтому предел,
		// на котором письмо ещё влезает целиком, выше прежнего.
		{"*см https://example.com тут*", 45},
		{"> текст `код` хвост", 27},  // отказ от code
		{"текст `код` хвост", 18},    // код строкой дешевле общего блока
		{"```\nкод\n```", 6},         // блок кода строкой: тег дороже тела
		{"- **раз** два\n- три", 27}, // выделение помещается
		{"# заголовок\n\nабзац с https://example.com/doc внутри", 72},
		{"*A **B** C*", 14},
	}

	for _, случай := range случаи {
		t.Run(случай.body, func(t *testing.T) {
			source, cutInput := boundInput(случай.body)
			got := (&renderSession{doc: parseSource(source), source: source}).choose(случай.budget, cutInput)

			if got.covered != got.total {
				t.Errorf("предел %d показал %d рун из %d (профиль %s): %q",
					случай.budget, got.covered, got.total, got.name, got.html)
			}
			if got.truncated {
				t.Errorf("предел %d: письмо целое, а обрезка объявлена: %q", случай.budget, got.html)
			}
		})
	}
}

