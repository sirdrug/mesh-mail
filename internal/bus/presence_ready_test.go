package bus

import (
	"context"
	"testing"
	"time"

	natsserver "github.com/nats-io/nats-server/v2/server"
	"github.com/nats-io/nats.go"
)

// TestПодпискаНаВизиткиГотоваКМоментуВозврата — подписка обязана быть
// зарегистрирована СЕРВЕРОМ к моменту, когда WatchPresence вернул управление.
//
// nc.Subscribe кладёт запрос в буфер соединения и возвращается, не дожидаясь
// сервера. Пока сервер о подписке не знает, всё опубликованное проходит мимо —
// молча, потому что Core NATS ничего не переигрывает. Барьером служит Flush:
// round-trip означает, что SUB обработан. Приём в проекте был и раньше —
// Announce делает Flush после Publish, — но на подписке его забыли.
//
// Спрашиваем САМ СЕРВЕР, а не доставку, и это решает вопрос о надёжности
// проверки. Детерминированной её делает ОТСУТСТВИЕ ОКНА: NumSubscriptions
// сообщает состояние сервера в тот же момент, и между возвратом WatchPresence
// и вопросом нет промежутка, в который что-то могло бы успеть.
//
// Прежняя редакция теста объявляла визитку, спала и смотрела в реестр — то
// есть шла через доставку, у которой окно есть: флашер соединения успевает не
// всегда. Поэтому сломанный код проходил примерно в трети одиночных попыток, и
// тест приходилось повторять полсотни раз, оставаясь вероятностным.
//
// Повторы сюда возвращать НЕ НАДО. Замер, на котором это выяснилось (без Flush
// сервер не видит подписку 100 раз из 100, с Flush видит все 100), —
// иллюстрация, а не основание: надёжность даёт устройство проверки, а не
// количество попыток. Если однажды тест покажется ненадёжным, искать причину
// нужно в появившемся окне, а не в числе прогонов.
//
// Доставку проверяет отдельный тест — TestAnnounceДоходитДоПодписчика. Свойства
// разные: здесь сервер ЗНАЕТ о подписке, там визитка ДОХОДИТ до реестра, и
// одно другого не заменяет.
//
// Своему серверу здесь есть причина: bustest отдаёт только адрес, а оракулу
// нужен сам сервер, чтобы спросить у него число подписок.
func TestПодпискаНаВизиткиГотоваКМоментуВозврата(t *testing.T) {
	ns, err := natsserver.NewServer(&natsserver.Options{Port: -1, NoLog: true, NoSigs: true})
	if err != nil {
		t.Fatalf("сервер: %v", err)
	}
	go ns.Start()
	if !ns.ReadyForConnections(5 * time.Second) {
		t.Fatal("сервер не поднялся")
	}
	t.Cleanup(ns.Shutdown)

	nc, err := nats.Connect(ns.ClientURL())
	if err != nil {
		t.Fatalf("подключение: %v", err)
	}
	t.Cleanup(nc.Close)

	// Соединение прогрето до измеряемого участка: считаем регистрацию
	// подписки, а не установление связи.
	if err := nc.Flush(); err != nil {
		t.Fatalf("прогрев соединения: %v", err)
	}
	before := ns.NumSubscriptions()

	ctx, cancel := context.WithCancel(context.Background())
	// Отмена до Shutdown: подписка снимается, горутина ожидания завершается,
	// и сервер не остаётся с висящим подписчиком.
	t.Cleanup(cancel)

	if err := WatchPresence(ctx, nc, NewRegistry()); err != nil {
		t.Fatalf("подписка: %v", err)
	}

	if got := ns.NumSubscriptions(); got != before+1 {
		t.Fatalf("сервер знает о %d подписках, ожидалось %d: WatchPresence вернул "+
			"управление раньше, чем сервер узнал о подписке — визитки, объявленные "+
			"в этом окне, потеряются молча", got, before+1)
	}
}
