package bus

// Разрыв и восстановление связи обязаны попадать в журнал.
//
// Проверяется ВЫЗОВ обработчиков, а не наличие опций в исходнике: строка
// `nats.DisconnectErrHandler(...)` в коде доказывает намерение, а не то, что
// клиент её позовёт. Поэтому сервер здесь настоящий, и он по-настоящему
// останавливается.

import (
	"bytes"
	"context"
	"log"
	"strings"
	"sync"
	"testing"
	"time"

	"github.com/boreevyuri/mesh-mail/internal/bustest"
)

// журнал — потокобезопасный приёмник строк.
//
// Обработчики зовутся из горутины клиента, а тест читает из своей: без
// синхронизации это гонка, которую -race поймает, а без него он падал бы
// изредка и необъяснимо.
type журнал struct {
	mu  sync.Mutex
	buf bytes.Buffer
}

func (ж *журнал) Write(p []byte) (int, error) {
	ж.mu.Lock()
	defer ж.mu.Unlock()
	return ж.buf.Write(p)
}

func (ж *журнал) текст() string {
	ж.mu.Lock()
	defer ж.mu.Unlock()
	return ж.buf.String()
}

// Обработчики разрыва и восстановления действительно зовутся.
//
// Дефект, ради которого написано: переподключение происходило молча, и
// единственным следом разрыва была случайная ошибка публикации, попавшая в то
// же окно. За день на маке набралось восемь таких строк, и по ним нельзя было
// отличить одну потерю связи от восьми.
func TestРазрывИВосстановлениеПопадаютВЖурнал(t *testing.T) {
	url, stop, start := bustest.StartRestartable(t)

	ж := &журнал{}
	conn, err := Connect(context.Background(), Options{
		URLs:   []string{url},
		Name:   "тестовый-узел",
		Logger: log.New(ж, "", 0),
	})
	if err != nil {
		t.Fatalf("подключение: %v", err)
	}
	t.Cleanup(conn.Close)

	stop()
	ждать(t, ж, "связь с хабом потеряна", "обработчик разрыва не позван")

	start()
	ждать(t, ж, "связь с хабом восстановлена", "обработчик восстановления не позван")

	// Восстановление обязано называть узел и хаб: строка нужна, чтобы понять,
	// КТО потерял связь и КУДА вернулся, когда в журнале рядом лежат сообщения
	// нескольких процессов.
	текст := ж.текст()
	if !strings.Contains(текст, "тестовый-узел") {
		t.Errorf("в журнале нет имени узла:\n%s", текст)
	}
	if !strings.Contains(текст, "127.0.0.1:") {
		t.Errorf("в журнале нет адреса хаба:\n%s", текст)
	}
}

// Учётные данные из адреса в журнал не попадают.
//
// `ConnectedUrl` возвращает адрес целиком, а он бывает вида
// `nats://user:pass@host`. Строка живёт в systemd дольше самой сессии, и
// пароль в ней — это утечка, которую никто не заметит.
func TestАдресВЖурналеБезУчётныхДанных(t *testing.T) {
	cases := []struct {
		имя, адрес, ожидаем string
	}{
		{"без учётных данных", "nats://127.0.0.1:4222", "127.0.0.1:4222"},
		{"с логином и паролем", "nats://agent:secret@hub.example:4222", "hub.example:4222"},
		{"только логин", "nats://agent@hub.example:4222", "hub.example:4222"},
		{"пустой адрес", "", ""},
		{"неразбираемый адрес", "://не-адрес", ""},
		// Кириллица в логине `url.Parse` не принимается вовсе — ошибка
		// `invalid userinfo`. Пустая строка здесь не потеря, а нужное
		// поведение: адрес, который мы не смогли разобрать, печатать нельзя,
		// потому что неизвестно, что в нём осталось.
		{"не-ASCII в учётных данных", "nats://агент:секрет@hub.example:4222", ""},
	}

	for _, c := range cases {
		t.Run(c.имя, func(t *testing.T) {
			got := safeHost(c.адрес)
			if got != c.ожидаем {
				t.Errorf("safeHost(%q) = %q, ожидалось %q", c.адрес, got, c.ожидаем)
			}
			if strings.Contains(got, "secret") || strings.Contains(got, "секрет") {
				t.Errorf("пароль просочился в журнал: %q", got)
			}
		})
	}
}

// ждать опрашивает журнал, пока в нём не появится строка.
func ждать(t *testing.T, ж *журнал, фрагмент, чтоНеТак string) {
	t.Helper()
	срок := time.Now().Add(10 * time.Second)
	for time.Now().Before(срок) {
		if strings.Contains(ж.текст(), фрагмент) {
			return
		}
		time.Sleep(20 * time.Millisecond)
	}
	t.Fatalf("%s: за 10 секунд в журнале не появилось %q.\nЖурнал:\n%s", чтоНеТак, фрагмент, ж.текст())
}

// Пароль из адреса подключения не доходит до журнала.
//
// Отдельный тест, потому что мутация показала дыру: если убрать safeHost из
// строки восстановления, оба прежних теста остаются зелёными. Юнит-тест
// проверяет саму функцию, интеграционный — обработчик, но подключался он по
// адресу без учётных данных, где сырой и безопасный вывод совпадают.
//
// Здесь адрес намеренно с логином и паролем. Сервер без авторизации их
// игнорирует, а `ConnectedUrl` возвращает как есть — то есть в журнал они
// попадут, если применение safeHost потеряется.
func TestПарольИзАдресаНеДоходитДоЖурнала(t *testing.T) {
	url, stop, start := bustest.StartRestartable(t)
	сУчётными := strings.Replace(url, "nats://", "nats://agent:s3cr3t@", 1)

	ж := &журнал{}
	conn, err := Connect(context.Background(), Options{
		URLs:   []string{сУчётными},
		Name:   "узел-с-паролем",
		Logger: log.New(ж, "", 0),
	})
	if err != nil {
		t.Fatalf("подключение по адресу с учётными данными: %v", err)
	}
	t.Cleanup(conn.Close)

	stop()
	start()
	ждать(t, ж, "связь с хабом восстановлена", "обработчик восстановления не позван")

	текст := ж.текст()
	if strings.Contains(текст, "s3cr3t") {
		t.Errorf("пароль попал в журнал:\n%s", текст)
	}
	if strings.Contains(текст, "agent:") {
		t.Errorf("учётные данные попали в журнал:\n%s", текст)
	}
	// Контроль: адрес хаба всё-таки записан, иначе тест был бы зелёным и при
	// пустой строке — то есть проверял бы не то.
	if !strings.Contains(текст, "127.0.0.1:") {
		t.Errorf("адрес хаба потерян целиком:\n%s", текст)
	}
}
