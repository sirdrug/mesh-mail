// Адресат, попавший и в To, и в CC, остаётся одним получателем.
//
// Различающий признак — ДЛИНА списка, а не его содержимое: письмо и с дублем
// адресовано «правильным» людям, поэтому проверка «получатель на месте»
// зелена в обоих случаях и не значит ничего. Цена дубля не в списке, а
// дальше: bus.Publish идёт по этому срезу и делает публикацию на каждый
// элемент, JetStream отбрасывает вторую по одинаковому Nats-Msg-Id, но
// core-подписчик успевает увидеть обе — и сторож будит агента дважды.
func TestRecipientsНеПовторяетАдресатаИзToИCC(t *testing.T) {
	m := New("pi-claude", []string{"m1-codex"}, "тема", "тело")
	m.CC = []string{"m1-codex"}

	got := m.Recipients()
	if len(got) != 1 {
		t.Fatalf("получателей %d (%v), а адресат один: каждая копия — лишнее пробуждение", len(got), got)
	}
	if got[0] != "m1-codex" {
		t.Fatalf("получатель %q, ожидался m1-codex", got[0])
	}
}

// Тот же адресат, повторённый внутри одного поля.
//
// Контроль к предыдущему тесту: дедупликация «только между To и CC» прошла бы
// его, а этот — нет.
func TestRecipientsНеПовторяетАдресатаВнутриОдногоПоля(t *testing.T) {
	m := New("pi-claude", []string{"m1-codex", "m1-codex"}, "тема", "тело")

	if got := m.Recipients(); len(got) != 1 {
		t.Fatalf("получателей %d (%v), а адресат один", len(got), got)
	}
}

// Порядок получателей не пляшет: сначала To в своём порядке, потом CC.
//
// Проверяется явно, потому что дедупликация через map порядок теряет, а от
// него зависит и тема публикации, и то, что человек видит в витрине. Тест на
// длину такую замену пропустил бы.
func TestRecipientsСохраняетПорядок(t *testing.T) {
	m := New("pi-claude", []string{"второй", "первый"}, "тема", "тело")
	m.CC = []string{"третий", "первый"}

	got := m.Recipients()
	want := []string{"второй", "первый", "третий"}
	if len(got) != len(want) {
		t.Fatalf("получателей %d (%v), ожидалось %d (%v)", len(got), got, len(want), want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Fatalf("получатель %d = %q, ожидался %q (весь список: %v)", i, got[i], want[i], got)
		}
	}
}

