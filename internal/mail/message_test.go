// Ответ нескольким не ускоряет предохранитель от циклов.
//
// Проверка к тому, что копия в ответах ничего не сломала в счётчике колен.
// Опасение звучало так: раз ответ теперь уходит троим, не начнёт ли предел
// срабатывать раньше в живом обсуждении. Не начнёт, и вот почему: hops
// считает ДЛИНУ ЦЕПОЧКИ, а не число писем и не число адресатов. Восемь
// ответов подряд дают восемь колен и при разговоре вдвоём, и при разговоре
// вшестером.
//
// Тест это фиксирует, потому что рассуждение легко забыть, а вот попытка
// «раз уж мы шлём троим, будем считать по получателям» выглядит правдоподобно
// и молча урезала бы длину обсуждения втрое.
func TestОтветНесколькимНеУскоряетСчётчикКолен(t *testing.T) {
	вшестером := New("pi-codex", []string{"mbp-claude", "pi-claude", "m1-claude"}, "тема", "тело")
	вшестером.CC = []string{"m1-codex", "studio-claude"}

	вдвоём := New("pi-codex", []string{"mbp-claude"}, "тема", "тело")

	a := вшестером.Reply("mbp-claude", "ответ")
	b := вдвоём.Reply("mbp-claude", "ответ")

	if a.Hops != b.Hops {
		t.Fatalf("одно колено дало hops=%d при шести участниках и hops=%d при двух", a.Hops, b.Hops)
	}
	if a.Hops != 1 {
		t.Fatalf("первое колено дало hops=%d, ожидалась единица", a.Hops)
	}
}

// Предел цепочки достигается ровно на восьмом колене и говорит об этом внятно.
//
// Отдельно от TestValidateОтвергаетПревышениеHops, который ставит счётчик
// руками: здесь цепочка набирается настоящими ответами, то есть проверяется
// связка Reply и Validate, а не значение поля.
func TestЦепочкаОтветовУпираетсяВПределИОбъясняетПричину(t *testing.T) {
	m := New("pi-codex", []string{"mbp-claude"}, "тема", "тело")
	m.CC = []string{"pi-claude"}

	who := []string{"mbp-claude", "pi-codex"}
	for колено := 1; колено < MaxHops; колено++ {
		m = m.Reply(who[колено%2], "продолжаем")
		if err := m.Validate(); err != nil {
			t.Fatalf("колено %d отвергнуто раньше предела: %v", колено, err)
		}
	}

	// Следующее — восьмое — уже за пределом.
	m = m.Reply(who[MaxHops%2], "и ещё одно")
	err := m.Validate()
	if err == nil {
		t.Fatalf("цепочка из %d колен прошла валидацию — предохранитель не сработал", MaxHops)
	}
	if !strings.Contains(err.Error(), "предела") {
		t.Fatalf("отказ не объясняет причину: %v", err)
	}
}
