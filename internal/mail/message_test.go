// Participants — все стороны разговора, каждая по разу.
//
// Отдельный метод, а не «From плюс Recipients» на месте вызова: складывать их
// руками приходилось витрине, и она складывала с дублем, когда отправитель
// сам оказывался среди получателей. Пока сложение живёт в одном месте с
// дедупликацией, повторить ту ошибку негде.
func TestParticipantsНеЗадваиваютОтправителя(t *testing.T) {
	m := New("pi-claude", []string{"pi-claude", "m1-codex"}, "тема", "тело")

	got := m.Participants()
	if len(got) != 2 {
		t.Fatalf("сторон %d (%v), ожидалось две", len(got), got)
	}
	if got[0] != "pi-claude" {
		t.Fatalf("первым идёт %q, ожидался отправитель pi-claude (список: %v)", got[0], got)
	}
}

// Отправитель идёт первым и не теряется среди получателей.
