func TestNewЗаполняетОбязательныеПоля(t *testing.T) {
	m := New("pi-claude", []string{"m1-codex"}, "тема", "тело")

	if m.ID == "" {
		t.Fatal("ID пустой — письмо нечем дедуплицировать")
	}
	if m.ThreadID == "" {
		t.Fatal("ThreadID пустой — переписка не соберётся в тред")
	}
	if m.Importance != ImportanceNormal {
		t.Fatalf("importance по умолчанию = %q, ожидался %q", m.Importance, ImportanceNormal)
	}
	if m.Hops != 0 {
		t.Fatalf("hops нового письма = %d, ожидался 0", m.Hops)
	}
	if m.CreatedAt.IsZero() {
		t.Fatal("CreatedAt не заполнен")
	}
}

