func TestReplyНаследуетТредИУвеличиваетHops(t *testing.T) {
	orig := New("pi-claude", []string{"m1-codex"}, "вопрос", "как дела")
	orig.Hops = 2

	r := orig.Reply("m1-codex", "нормально")

	if r.ThreadID != orig.ThreadID {
		t.Fatalf("тред не унаследован: %q != %q", r.ThreadID, orig.ThreadID)
	}
	if r.Hops != 3 {
		t.Fatalf("hops = %d, ожидалось 3", r.Hops)
	}
	if len(r.To) != 1 || r.To[0] != "pi-claude" {
		t.Fatalf("ответ адресован %v, ожидался [pi-claude]", r.To)
	}
	if r.ID == orig.ID {
		t.Fatal("у ответа тот же ID — дедупликация съест ответ")
	}
}

