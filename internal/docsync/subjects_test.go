// Сверка README с тем, что документ описывает СЛОВАМИ, а не таблицей.
//
// Первая версия сверки проверяла таблицу полей и список хранилищ — и на
// README до правки осталась зелёной. То есть покрывала не тот класс ошибок,
// ради которого затевалась: расходились схема тем, имя consumer'а и права,
// а всё это живёт в прозе и в примерах, не в таблицах.
//
// Здесь проверяется ровно то, что разошлось.

import (
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"

	"github.com/boreevyuri/mesh-mail/internal/bus"
)

// Схема темы письма в README совпадает с тем, что строит код.
//
// Прежняя редакция обещала `mail.<agent_id>`, а тема давно двухтокенная:
// `mail.<получатель>.<отправитель>`. Разница не косметическая — во втором
// токене живёт удостоверение отправителя, и, не зная о нём, читатель не
// поймёт, почему представиться `human` нельзя.
func TestСхемаТемыПисьмаСовпадаетСКодом(t *testing.T) {
	text := readme(t)

	// Образец из кода: по нему видно и число токенов, и порядок.
	образец := bus.MailSubject("получатель", "отправитель")
	if образец != "mail.получатель.отправитель" {
		t.Fatalf("MailSubject изменился: %q — сверка ниже потеряла смысл", образец)
	}

	const вДокументе = "mail.<получатель>.<отправитель>"
	if !strings.Contains(text, вДокументе) {
		t.Errorf("в README нет схемы %q, а код строит %q", вДокументе, образец)
	}

	// Односторонней проверки мало: старая схема могла остаться рядом с новой,
	// и читатель наткнулся бы на ту, что выше.
	устаревшая := regexp.MustCompile(`mail\.<agent_id>|mail\.<ID>([^.>]|$)`)
	if m := устаревшая.FindString(text); m != "" {
		t.Errorf("в README осталась однотокенная схема темы: %q", m)
	}
}

// Имя consumer'а ящика в README совпадает с кодом.
//
// README называет его `inbox-<agent_id>`, и это не деталь реализации: под
// случайное имя пришлось бы выдать право шаблоном `MSG.NEXT.MAIL.>`, а с ним
// агент читает чужой ящик. Документ, обещающий ordered consumer, подсказывает
// изменение, которое открывает переписку.
func TestИмяConsumerАЯщикаСовпадаетСКодом(t *testing.T) {
	text := readme(t)

	if got := bus.InboxConsumer("агент"); got != "inbox-агент" {
		t.Fatalf("InboxConsumer изменился: %q — сверка ниже потеряла смысл", got)
	}
	if !strings.Contains(text, "inbox-<agent_id>") {
		t.Error("в README нет имени consumer'а `inbox-<agent_id>`")
	}
	// Прежняя формулировка не должна вернуться незамеченной.
	if regexp.MustCompile(`(?i)чтение идёт через ordered consumer`).MatchString(text) {
		t.Error("в README вернулось «чтение идёт через ordered consumer»")
	}
}

// Права, перечисленные в README, существуют в шаблоне hub.conf — и наоборот,
// названные отсутствующими действительно отсутствуют у агента.
//
// Самое опасное место проекта: ошибка тихо открывает чужую переписку.
// Документ здесь не пересказ, а карта, по которой человек правит боевой
// конфиг.
func TestПраваИзREADMEСовпадаютСШаблономХаба(t *testing.T) {
	text := readme(t)
	conf := hubConf(t)

	// Права агента в README записаны с подстановкой `<ID>`; в шаблоне на её
	// месте стоят настоящие идентификаторы. Сверяем по образцу pi-claude:
	// он есть в шаблоне и не менялся с первого развёртывания.
	const образец = "pi-claude"

	вДокументе := regexp.MustCompile(`\$JS\.API\.[A-Z.]*[A-Za-z0-9.<>_*-]+`).FindAllString(text, -1)
	if len(вДокументе) < 4 {
		t.Fatalf("из README разобрано %d прав (%v) — парсер сломался", len(вДокументе), вДокументе)
	}

	for _, право := range вДокументе {
		право = strings.TrimSuffix(право, ".")
		реальное := strings.ReplaceAll(право, "<ID>", образец)
		реальное = strings.ReplaceAll(реальное, "<agent_id>", образец)

		// Права, названные отсутствующими, проверяются отдельным тестом ниже:
		// здесь нужны только те, что README обещает выданными.
		if строкаПроОтсутствие(text, право) {
			continue
		}
		if !strings.Contains(conf, реальное) {
			t.Errorf("README обещает право %q, в nats/hub.conf его нет (искали %q)", право, реальное)
		}
	}
}

// Права, названные в README отсутствующими, у агента действительно отсутствуют.
func TestОтсутствующиеПраваДействительноОтсутствуют(t *testing.T) {
	conf := hubConf(t)

	// Блок прав агента: до первой учётки моста. Мосту часть этих прав выдана
	// намеренно, и искать их во всём файле значило бы ловить его строки.
	конецАгентов := strings.Index(conf, `"mail.*.human"`)
	if конецАгентов < 0 {
		t.Fatal("в hub.conf не найден блок моста — разметка файла изменилась")
	}
	агентские := conf[:конецАгентов]

	запрещённые := []string{
		"$JS.API.STREAM.MSG.GET.MAIL",
		"$JS.API.DIRECT.GET.MAIL",
		"$JS.API.CONSUMER.LIST.MAIL",
		"$JS.API.CONSUMER.NAMES",
		"$JS.API.STREAM.CREATE.MAIL",
		"$JS.API.STREAM.UPDATE.MAIL",
	}
	for _, право := range запрещённые {
		if strings.Contains(агентские, право) {
			t.Errorf("право %q выдано агенту, хотя README называет его отсутствующим", право)
		}
	}

	// Контроль оракула: отрезок действительно содержит агентские права, а не
	// пуст из-за сдвига границы.
	if !strings.Contains(агентские, "$JS.API.CONSUMER.MSG.NEXT.MAIL.inbox-pi-claude") {
		t.Error("в отрезке агентских прав нет ожидаемой строки — граница блока найдена неверно")
	}
}

// строкаПроОтсутствие отвечает, упомянуто ли право в списке «чего нет».
func строкаПроОтсутствие(text, право string) bool {
	начало := strings.Index(text, "Чего намеренно нет")
	if начало < 0 {
		return false
	}
	конец := strings.Index(text[начало:], "\n---")
	if конец < 0 {
		конец = len(text) - начало
	}
	return strings.Contains(text[начало:начало+конец], право)
}

// hubConf читает шаблон прав хаба БЕЗ комментариев.
//
// Комментарии выбрасываются не для красоты: в шапке файла перечислены
// запрещённые права с объяснением, почему их нет. Поиск подстроки по всему
// файлу находит их и объявляет выданными — тест на этом и споткнулся,
// сообщив о дефекте, которого нет.
func hubConf(t *testing.T) string {
	t.Helper()
	path := filepath.Join("..", "..", "nats", "hub.conf")
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("чтение %s: %v", path, err)
	}

	var live []string
	for _, line := range strings.Split(string(data), "\n") {
		if strings.HasPrefix(strings.TrimSpace(line), "#") {
			continue
		}
		live = append(live, line)
	}
	return strings.Join(live, "\n")
}
